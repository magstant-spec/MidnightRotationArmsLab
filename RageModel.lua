local addonName, addon = ...

-- ---------------------------------------------------------------------------
-- Running rage estimate (0.5.3)
--
-- Midnight hides rage, rage percent and attack speed, even out of combat. The
-- rage probe showed what is still readable:
--   * UNIT_POWER_FREQUENT fires for every rage change (amount hidden)
--   * spell rage costs (C_Spell.GetSpellPowerCost) stay readable in combat
--   * C_Spell.IsSpellUsable's "not enough resource" flag stays readable
--   * the player's own successful casts
-- The model adds known generator amounts on casts, subtracts exact costs on
-- spenders, treats unexplained rage-change events as auto-attacks, and pins
-- itself to the true value whenever a spender's "not enough rage" flag flips
-- (that moment means rage is exactly at that spell's cost). The auto-attack
-- gain is learned from those corrections.
-- ---------------------------------------------------------------------------

local RageModel = {}
addon.RageModel = RageModel

local RAGE = (Enum and Enum.PowerType and Enum.PowerType.Rage) or 1
local DEFAULT_MAX_RAGE = 120
local EXPLAINED_WINDOW = 0.35
local DUPLICATE_CAST_WINDOW = 0.20

-- Rage generated by casts (by spell name). Starting points; tune with
-- /midrotlab rage debug and the trace fields.
local GENERATION = {
    ["Charge"] = 20,
    ["Bloodthirst"] = 8,
    ["Bloodbath"] = 8,
    ["Raging Blow"] = 12,
    ["Crushing Blow"] = 12,
    ["Odyn's Fury"] = 15,
    ["Thunder Blast"] = 5,
    ["Thunder Clap"] = 5,
    ["Whirlwind"] = 3,
    ["Bladestorm"] = 20,
    ["Ravager"] = 20,
    ["Skullsplitter"] = 15,
    ["Overpower"] = 0,
    ["Recklessness"] = 0,
}

-- Costs that override C_Spell.GetSpellPowerCost. The API reported 50 for
-- Rampage on live 12.1.5, but in-game it costs 80 (user-verified); the
-- usability flag flips at the real cost, so anchors must use the real value.
local COST_OVERRIDES = {
    [184367] = 80, -- Rampage
}

-- Spells whose usability flips are used as exact anchors. Costs are read live.
local ANCHOR_SPELLS = {
    184367, -- Rampage
    12294,  -- Mortal Strike
    1464,   -- Slam
    845,    -- Cleave
    772,    -- Rend
    6343,   -- Thunder Clap
    1680,   -- Whirlwind (Arms)
    5308,   -- Execute
    280735, -- Execute (Fury)
    163201, -- Execute (Arms)
    190456, -- Ignore Pain
    202168, -- Impending Victory
    1715,   -- Hamstring
}

local state = {
    estimate = 0,
    max = DEFAULT_MAX_RAGE,
    autoGain = 8,
    autoCount = 0,
    autosSinceAnchor = 0,
    lastCastAt = 0,
    lastCastName = nil,
    lastAnchorAt = 0,
    lastAnchorError = 0,
    anchors = 0,
    reckUntil = 0,
    usable = {},
    costCache = {},
}

local function IsSecret(value)
    if issecretvalue then
        local ok, secret = pcall(issecretvalue, value)
        return ok and secret == true
    end
    return false
end

local function Readable(value)
    if value == nil or IsSecret(value) then
        return nil
    end
    local ok = pcall(function() return value + 0 end)
    return ok and value or nil
end

local function IsWarrior()
    local _, classToken = UnitClass("player")
    return classToken == "WARRIOR"
end

local function Known(spellID)
    if IsPlayerSpell then
        local ok, known = pcall(IsPlayerSpell, spellID)
        if ok and known == true then
            return true
        end
    end
    if C_SpellBook and C_SpellBook.IsSpellInSpellBook then
        local ok, known = pcall(C_SpellBook.IsSpellInSpellBook, spellID)
        return ok and known == true
    end
    return false
end

local function RageCost(spellID)
    if COST_OVERRIDES[spellID] then
        return COST_OVERRIDES[spellID]
    end
    local cached = state.costCache[spellID]
    if cached ~= nil then
        return cached or nil
    end
    if not C_Spell or not C_Spell.GetSpellPowerCost then
        return nil
    end
    local ok, costs = pcall(C_Spell.GetSpellPowerCost, spellID)
    if not ok or type(costs) ~= "table" then
        return nil
    end
    local okRead, cost = pcall(function()
        for _, entry in ipairs(costs) do
            if entry.type == RAGE then
                return entry.cost
            end
        end
        return false
    end)
    if not okRead then
        return nil
    end
    if cost ~= false then
        cost = Readable(cost)
        if cost == nil then
            return nil
        end
    end
    state.costCache[spellID] = cost
    return cost or nil
end

local function Clamp()
    if state.estimate < 0 then
        state.estimate = 0
    elseif state.estimate > state.max then
        state.estimate = state.max
    end
end

local function ReadMaxRage()
    if not UnitPowerMax then
        return
    end
    local ok, maximum = pcall(UnitPowerMax, "player", RAGE)
    maximum = ok and Readable(maximum) or nil
    if maximum and maximum > 0 then
        state.max = maximum
    end
end

-- Exact readings, when Midnight allows them (it currently does not).
local function TryReadExact()
    local ok, power = pcall(UnitPower, "player", RAGE)
    power = ok and Readable(power) or nil
    if power then
        state.estimate = power
        state.exact = true
        return true
    end
    state.exact = false
    return false
end

local function Anchor(value, reason)
    local error = value - state.estimate
    state.lastAnchorError = error
    state.lastAnchorAt = GetTime()
    state.anchors = state.anchors + 1

    -- Learn the auto-attack gain: spread the correction over the autos seen
    -- since the previous anchor (small step, clamped to sane values).
    if state.autosSinceAnchor >= 2 then
        local perAuto = error / state.autosSinceAnchor
        state.autoGain = math.max(2, math.min(25, state.autoGain + perAuto * 0.25))
    end
    state.autosSinceAnchor = 0
    state.estimate = value
    state.lastAnchorReason = reason
    Clamp()
end

-- Usability constraints from every known rage spender. A flip from "short on
-- rage" to "enough" means rage just reached that cost; the reverse means it
-- just fell below it. While steady, the flags bound the estimate.
local function ApplyUsabilityConstraints()
    if not C_Spell or not C_Spell.IsSpellUsable then
        return
    end

    for _, spellID in ipairs(ANCHOR_SPELLS) do
        if Known(spellID) then
            local cost = RageCost(spellID)
            if cost and cost > 0 then
                local ok, _, noResource = pcall(C_Spell.IsSpellUsable, spellID)
                if ok and type(noResource) == "boolean" and not IsSecret(noResource) then
                    local enough = not noResource
                    local previous = state.usable[spellID]
                    state.usable[spellID] = enough

                    if previous == false and enough then
                        -- Rage only rises in steps, so it has just landed a
                        -- little above this cost.
                        Anchor(cost + 2, "reached " .. cost)
                    elseif enough and state.estimate < cost then
                        Anchor(cost, "at least " .. cost)
                    elseif not enough and state.estimate >= cost then
                        Anchor(cost - 1, "below " .. cost)
                    end
                end
            end
        end
    end
end

local function GenerationMultiplier()
    if GetTime() < state.reckUntil then
        return 2.0
    end
    return 1.0
end

local function OnCast(spellID)
    local name = C_Spell and C_Spell.GetSpellName and C_Spell.GetSpellName(spellID) or nil
    if type(name) ~= "string" or IsSecret(name) then
        return
    end

    local now = GetTime()
    if name == state.lastCastName and (now - state.lastCastAt) < DUPLICATE_CAST_WINDOW then
        return
    end
    state.lastCastName = name
    state.lastCastAt = now

    if name == "Recklessness" then
        state.reckUntil = now + 12
    end

    local cost = RageCost(spellID)
    if cost and cost > 0 then
        local spend = cost
        if name == "Execute" then
            -- Execute can consume extra rage above its base cost.
            spend = math.min(state.estimate, cost + 20)
        end
        state.estimate = state.estimate - spend
    end

    local gain = GENERATION[name]
    if gain then
        state.estimate = state.estimate + gain * GenerationMultiplier()
    end
    Clamp()
end

local function OnPowerChanged()
    local now = GetTime()
    if (now - state.lastCastAt) <= EXPLAINED_WINDOW then
        return
    end
    -- Unexplained rage change in combat: almost always an auto-attack.
    if UnitAffectingCombat("player") then
        state.autoCount = state.autoCount + 1
        state.autosSinceAnchor = state.autosSinceAnchor + 1
        state.estimate = state.estimate + state.autoGain * GenerationMultiplier()
        Clamp()
    end
end

local frame = CreateFrame("Frame")
frame:RegisterEvent("PLAYER_LOGIN")
frame:SetScript("OnEvent", function(_, event, unit, arg2, arg3)
    if event == "PLAYER_LOGIN" or event == "PLAYER_SPECIALIZATION_CHANGED" then
        frame:UnregisterAllEvents()
        frame:RegisterEvent("PLAYER_SPECIALIZATION_CHANGED")
        if IsWarrior() then
            frame:RegisterEvent("PLAYER_REGEN_DISABLED")
            frame:RegisterEvent("PLAYER_REGEN_ENABLED")
            frame:RegisterUnitEvent("UNIT_POWER_FREQUENT", "player")
            frame:RegisterUnitEvent("UNIT_SPELLCAST_SUCCEEDED", "player")
            wipe(state.costCache)
            wipe(state.usable)
            ReadMaxRage()
        end
        return
    end

    if event == "PLAYER_REGEN_DISABLED" then
        if not TryReadExact() then
            -- Rage decays to zero out of combat; a Charge that opened the
            -- fight has already added its rage. Usability fixes the rest.
            local chargedIn = state.lastCastName == "Charge" and (GetTime() - state.lastCastAt) < 2
            state.estimate = chargedIn and (GENERATION["Charge"] or 0) or 0
        end
        state.autosSinceAnchor = 0
        wipe(state.usable)
        return
    end

    if event == "PLAYER_REGEN_ENABLED" then
        state.reckUntil = 0
        return
    end

    if event == "UNIT_SPELLCAST_SUCCEEDED" then
        OnCast(arg3)
        return
    end

    if event == "UNIT_POWER_FREQUENT" then
        if type(arg2) == "string" and not IsSecret(arg2) and arg2 ~= "RAGE" then
            return
        end
        OnPowerChanged()
    end
end)

-- Called by the engine every update. Returns the estimate (rounded) and
-- whether it is exact.
function RageModel:Update()
    if not IsWarrior() then
        return nil, false
    end
    if TryReadExact() then
        return state.estimate, true
    end
    ApplyUsabilityConstraints()
    return math.floor(state.estimate + 0.5), false
end

function RageModel:GetDebug()
    return {
        estimate = math.floor(state.estimate + 0.5),
        exact = state.exact == true,
        max = state.max,
        autoGain = state.autoGain,
        autoCount = state.autoCount,
        anchors = state.anchors,
        lastAnchorError = state.lastAnchorError,
        lastAnchorReason = state.lastAnchorReason,
    }
end

-- ---------------------------------------------------------------------------
-- Optional readout: real rage (displayed through the secret-safe SetText path,
-- never read by Lua) next to the estimate, for calibration by eye.
-- ---------------------------------------------------------------------------

local readout
local function EnsureReadout()
    if readout then
        return readout
    end
    readout = CreateFrame("Frame", nil, UIParent)
    readout:SetSize(220, 24)
    readout:SetPoint("CENTER", UIParent, "CENTER", 0, -220)
    readout:SetMovable(true)
    readout:EnableMouse(true)
    readout:RegisterForDrag("LeftButton")
    readout:SetScript("OnDragStart", readout.StartMoving)
    readout:SetScript("OnDragStop", readout.StopMovingOrSizing)

    readout.real = readout:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge")
    readout.real:SetPoint("LEFT", readout, "LEFT", 0, 0)
    readout.est = readout:CreateFontString(nil, "OVERLAY", "GameFontHighlightLarge")
    readout.est:SetPoint("LEFT", readout.real, "RIGHT", 12, 0)

    readout.elapsed = 0
    readout:SetScript("OnUpdate", function(self, elapsed)
        self.elapsed = self.elapsed + elapsed
        if self.elapsed < 0.1 then
            return
        end
        self.elapsed = 0
        local ok, real = pcall(UnitPower, "player", RAGE)
        if ok then
            -- SetText accepts secret values; Lua never inspects them.
            pcall(self.real.SetText, self.real, real)
        end
        local estimate = RageModel:Update()
        self.est:SetText(string.format("est %s  (auto %.1f)", tostring(estimate or "?"), state.autoGain))
    end)
    readout:Hide()
    return readout
end

function addon:RageModelCommand(argument)
    if argument == "debug" or argument == "" or argument == nil then
        local frameRef = EnsureReadout()
        if frameRef:IsShown() then
            frameRef:Hide()
            self:Print("Rage readout hidden.")
        else
            frameRef:Show()
            self:Print("Rage readout shown: left is your real rage (display only), right is the addon's estimate. Drag to move.")
        end
        return
    end

    local debug = RageModel:GetDebug()
    self:Print(string.format("Rage estimate %d (exact %s), max %d, auto gain %.1f over %d autos, %d anchors, last correction %+.0f (%s)",
        debug.estimate, tostring(debug.exact), debug.max, debug.autoGain, debug.autoCount, debug.anchors,
        debug.lastAnchorError or 0, tostring(debug.lastAnchorReason or "none")))
end
